"""Level suite (LS): instances balanced over certified Levels 1-4 and no continuation.

docs/SCENARIO_DESIGN_2026_10_14.md, Section 4. A draw is one instance (mission,
strength, update time) generated by a recipe aimed at a target class. Recipes only
change which draws are tried; a draw enters a class only through its certified
minimum from the reference run, and an undecided draw goes to the hard-residue
pool. Every draw is a new base mission, so no base mission appears twice. Level-4
draws are constructed around a Level-4 witness (``level4.py``) and screened by a
plan search at Levels 0-3, which rejects only draws that cannot be Level 4.
"""
