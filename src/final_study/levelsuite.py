CLASS_NAMES = ('1', '2', '3', '4', 'infinity')


def draw_id(target, fleet, index):
    return f'LS_{"inf" if target == "infinity" else "L"+target}_m{fleet}_{index:04d}'


def _cells_after(p, tau, fraction):
    """(uid, slot, cell, leg) for legs into tasks whose cell is entered after the update time."""
    s = Scenario(p)
    out = []
    for leg in leg_windows(p):
        if leg['site'] == 'DEPOT':
            continue
        t = leg['start'][0]
        for a, b, cell in split_static_path(s, leg['path']):
            if a == b:
                continue
            if t >= fraction*tau:
                out.append((leg['uid'], leg['slot'], cell, leg))
            t += stationary_duration(s, leg['uid'], [list(map(float, a)), list(map(float, b))])[0]
    return out


def _blocks(p):
    """Every 2 x 2 block of wind cells, as a sorted tuple of cell indices."""
    lows = [tuple(min(Fraction(str(v[i])) for v in c['polygon_xy']) for i in (0, 1)) for c in p['wind']['cells']]
    xs, ys = sorted({x for x, _ in lows}), sorted({y for _, y in lows})
    at = {low: i for i, low in enumerate(lows)}
    out = []
    for a in range(len(xs)-1):
        for b in range(len(ys)-1):
            block = [at.get((xs[a+i], ys[b+j])) for i in (0, 1) for j in (0, 1)]
            if None not in block:
                out.append(tuple(sorted(block)))
    return out


def _inward(p, block):
    """The direction among the 12 that points most nearly from the block's centre to the depot,
    so legs flying out of the depot through the block meet a headwind; None if the depot is
    the centre."""
    corners = [v for c in block for v in p['wind']['cells'][c]['polygon_xy']]
    cx = sum(Fraction(str(v[0])) for v in corners)/len(corners)
    cy = sum(Fraction(str(v[1])) for v in corners)/len(corners)
    dx, dy = (Fraction(str(p['mission']['depot_xy'][0]))-cx, Fraction(str(p['mission']['depot_xy'][1]))-cy)
    if dx == dy == 0:
        return None
    return max(DIRECTIONS, key=lambda v: Fraction(v[0])*dx+Fraction(v[1])*dy)


def _last_cell(p, path):
    """Index of the wind cell a leg ends in (the cell of its last piece)."""
    return [cell for a, b, cell in split_static_path(Scenario(p), path) if a != b][-1]


def _u0(p, cell, direction, strength, time, rule):
    """U0 of an update (None if the snapshot or the previous premise fails); reads no label."""
    try:
        scenario = Scenario(build_variants(p, cell, direction, (strength,), (time,), rule=rule)[0, 0])
    except ValueError:
        return None
    if not previous_premise(scenario)['accepted']:
        return None
    return affected_uavs(scenario, diagnose_wind_update(scenario))['uavs']


def _in_cells(p, cells, xy):
    """True if a point lies in one of the (axis-aligned) wind cells."""
    for c in cells:
        polygon = p['wind']['cells'][c]['polygon_xy']
        xs, ys = [v[0] for v in polygon], [v[1] for v in polygon]
        if min(xs) <= xy[0] <= max(xs) and min(ys) <= xy[1] <= max(ys):
            return True
    return False


def _remaining_route(p, uid, after, times):
    """Points a UAV's incumbent route still passes after time ``after``: from its last stop
    before then, through its remaining stops, back to the depot (previous forecast)."""
    route = p['incumbent']['routes'][uid]
    depot = p['mission']['depot_xy']
    position = {t['id']: t['position_xy'] for t in p['mission']['tasks']}
    stops = route['stops'][:active_count(route)]
    points = [depot]+[depot if x == 'DEPOT' else position[x] for x in stops]+[depot]
    keys = [None]+list(stops)+[None]
    first = next((i for i, x in enumerate(keys) if x in times and times[x][1] > after), len(points)-1)
    return points[max(0, first-1):]


def _distance(xy, points):
    """Distance from a point to a polyline (km)."""
    best = math.dist(xy, points[0])
    for a, b in zip(points, points[1:]):
        dx, dy = b[0]-a[0], b[1]-a[1]
        length = dx*dx+dy*dy
        k = 0 if length == 0 else max(0, min(1, ((xy[0]-a[0])*dx+(xy[1]-a[1])*dy)/length))
        best = min(best, math.dist(xy, (a[0]+k*dx, a[1]+k*dy)))
    return best


def _rescuer_gap(p, task, owner, after, times):
    """How much nearer the nearest other UAV's remaining route passes a task than the second
    nearest (km): large when exactly one other UAV is placed to reach it in time."""
    xy = next(t['position_xy'] for t in p['mission']['tasks'] if t['id'] == task)
    near = sorted(_distance(xy, _remaining_route(p, v, after, times))
                  for v in p['incumbent']['routes'] if v != owner)
    return near[1]-near[0] if len(near) > 1 else 0.


def _recipe(target, index):
    if target == '2':
        return 'reorder' if index % 2 == 0 else 'recharge'
    if target == '4':
        return MECHANISMS[index % 2]
    return {'1': 'ordinary', '3': 'helper', 'infinity': 'blocked'}[target]


def ls_draw(target, fleet, index, *, base_seed, sigma_values=None, beta_values=None, rule='D1p',
            admission_seconds=30, screen_seconds=120, tighten_rounds=8):
    """Return (payload or None, ledger) for one draw."""
    sigma_values, beta_values = sigma_values or SIGMA, beta_values or BETA
    seed = int(digest(dict(target=target, fleet=fleet, index=index, base=base_seed))[:12], 16)
    rng = random.Random(seed)
    recipe = _recipe(target, index)
    ti = index % 3
    fraction = Fraction(TIMES[ti])
    k = rng.choice((3, 4)) if recipe in ('reorder', *MECHANISMS) else rng.choice((2, 3, 4))
    loosest = max(sigma_values, key=lambda s: Fraction(sigma_values[s]))
    tightest = min(sigma_values, key=lambda s: Fraction(sigma_values[s]))
    smallest_battery = min(beta_values, key=lambda b: Fraction(beta_values[b]))
    sigma = (loosest if recipe in ('recharge', 'reorder') else tightest if recipe == 'blocked'
             else rng.choice(sorted(sigma_values)))
    beta = smallest_battery if recipe == 'recharge' else rng.choice(sorted(beta_values))
    ri = 2 if recipe in ('recharge', 'blocked', *MECHANISMS) else rng.randrange(3)
    family = rng.choice(('uniform', 'clustered'))
    name = draw_id(target, fleet, index)
    ledger = dict(version='final-study-ls-draw-v1', draw=name, target=target, recipe=recipe, fleet=fleet, k=k,
                  sigma=sigma, beta=beta, strength=STRENGTHS[ri], time=TIMES[ti], family=family, seed=seed,
                  status='rejected', reason=None, selection_uses_recovery_labels=False)
    p = _geometry(fleet*k, fleet, family, seed % 10**8, rng)
    p['wind']['speed_bound_kmh'] = .8
    if recipe in MECHANISMS:
        # The constructions give deliveries to helpers, which must load new goods at the depot:
        # in flight, the moved deliveries' goods are already on board the affected UAVs. The
        # depot holds the generator's largest stock, 1.5 x total demand (amended 17 October).
        demand = sum(Fraction(str(t['demand'])) for t in p['mission']['tasks'])
        p['state']['depot_stock'] = float(demand*Fraction(3, 2))
    battery_reference(p, Fraction(beta_values[beta]))
    times = previous_delivery_times(p)
    tau = max(hi for _, hi in times.values())
    classes = assign_classes(times, rng)
    options = _cells_after(p, tau, fraction)
    if not options:
        ledger['reason'] = 'no_leg_ahead'
        return None, ledger
    routes = p['incumbent']['routes']
    position = {t['id']: tuple(t['position_xy']) for t in p['mission']['tasks']}
    chosen = cells = None
    if recipe in ('reorder',):
        late_urgent = [o for o in options if o[1] > 1]
        if late_urgent:
            chosen = rng.choice(late_urgent)
            classes[chosen[3]['site']] = 1
    elif recipe == 'recharge':
        longest = max(options, key=lambda o: o[3]['end'][1]-o[3]['start'][0])
        chosen = longest
    elif recipe == 'helper':
        near = []
        for o in options:
            site = o[3]['site']
            for uid, r in routes.items():
                if uid != o[0] and any(s in position and math.dist(position[s], position[site]) <= .3 for s in r['stops']):
                    near.append((o, uid))
                    break
        if near:
            (chosen, helper) = rng.choice(near)
            classes[chosen[3]['site']] = 1
            for s in routes[helper]['stops']:
                if s in classes:
                    classes[s] = rng.choice((10, 50))
    elif recipe == 'deficit':
        # The construction below sets the deadlines that matter. Here: a 2 x 2 block of cells
        # (one cell rarely slows two UAVs; amended 16 October), the wind blowing toward the depot
        # so that outbound legs through the block fly into it. Preferred, in order (amended 16
        # October): two or more affected UAVs with deliveries still to make inside the block (they
        # cannot fly around it); exactly two affected UAVs when the fleet allows (each then loses
        # a task to its own helper); more such deliveries.
        owner = p['incumbent']['assignment']
        position = {t['id']: t['position_xy'] for t in p['mission']['tasks']}
        scores = {}
        for block in _blocks(p):
            inward = _inward(p, block)
            u0_block = inward and _u0(p, block, inward, STRENGTHS[ri], TIMES[ti], rule)
            if not u0_block or len(u0_block) > fleet//2:
                continue
            inside = [t for t, (_, hi) in times.items() if hi > fraction*tau and owner.get(t) in u0_block
                      and _in_cells(p, block, position[t])]
            scores[block] = (min(len({owner[t] for t in inside}), 2),
                             -abs(len(u0_block)-2) if fleet > 4 else -len(u0_block), len(inside))
        ledger['block_scores'] = {'+'.join(p['wind']['cells'][c]['id'] for c in b): list(v)
                                  for b, v in sorted(scores.items())}
        if scores:
            top = max(scores.values())
            cells = rng.choice(sorted(b for b, v in scores.items() if v == top))
    elif recipe == 'chain':
        # The construction below sets the deadlines that matter. Here: a leg into a task that lies
        # in the cell (no path avoids the headwind), in a cell that affects as few UAVs as
        # possible (one if any), so U0 plus one helper leaves most of the fleet out. Among those
        # (amended 16 October): the task that one other UAV's remaining route passes much nearer
        # than any other's, so that only one helper is placed to deliver it on time.
        inside = [o for o in options if o[2] == _last_cell(p, o[3]['path'])]
        options = inside or options
        sizes = {}
        for o in rng.sample(options, len(options)):
            if o[2] not in sizes:
                u0_cell = _u0(p, o[2], headwind(o[3]['path']), STRENGTHS[ri], TIMES[ti], rule)
                sizes[o[2]] = u0_cell and len(u0_cell)
        fewest = min((n for n in sizes.values() if n), default=None)
        if fewest is not None:
            candidates = [o for o in options if sizes[o[2]] == fewest]
            gaps = [_rescuer_gap(p, o[3]['site'], o[0], fraction*tau, times) for o in candidates]
            chosen = rng.choice([o for o, g in zip(candidates, gaps) if g == max(gaps)])
            ledger.update(u0_sizes={p['wind']['cells'][c]['id']: n for c, n in sorted(sizes.items())},
                          rescuer_gap_km=max(gaps))
    elif recipe == 'blocked':
        chosen = rng.choice(options)
        classes[chosen[3]['site']] = 1
    if cells is not None:
        direction = _inward(p, cells)
        ledger.update(leg=None, cell=[p['wind']['cells'][c]['id'] for c in cells])
    else:
        if chosen is None:
            chosen = rng.choice(options)
            ledger['fallback'] = 'ordinary placement'
        uid, slot, cell, leg = chosen
        cells = cell
        direction = rng.choice(DIRECTIONS) if recipe == 'ordinary' else headwind(leg['path'])
        ledger.update(leg=[uid, slot], cell=p['wind']['cells'][cell]['id'])
    due = deadlines(times, tau, classes, Fraction(sigma_values[sigma]))
    for t in p['mission']['tasks']:
        t['deadline_h'] = due[t['id']]
    ledger.update(direction=list(map(str, direction)), classes=classes, tau=str(tau), aimed=recipe != 'ordinary')
    try:
        payload = build_variants(p, cells, direction, (STRENGTHS[ri],), (TIMES[ti],), rule=rule)[0, 0]
    except ValueError as error:
        ledger['reason'] = 'snapshot_failed: '+str(error)
        return None, ledger
    payload['benchmark_id'] = name
    scenario = Scenario(payload)
    # The previous-wind premise first: the U0 diagnosis needs it (in-flight draws can fail it).
    if not previous_premise(scenario)['accepted']:
        ledger['reason'] = 'previous_premise_failed'
        return None, ledger
    u0 = affected_uavs(scenario, diagnose_wind_update(scenario))['uavs']
    ledger['affected'] = u0
    if not 0 < len(u0) <= fleet//2:
        ledger['reason'] = 'not_local'
        return None, ledger
    if recipe in MECHANISMS:
        built = construct(payload, recipe, {t: hi for t, (_, hi) in times.items()})
        if built is None:
            ledger['reason'] = 'no_construction'
            return None, ledger
        plan, due, info = built
        changed = {}
        for t in p['mission']['tasks']:
            if t['id'] in due and due[t['id']] != Fraction(str(t['deadline_h'])):
                t['deadline_h'] = _decimal(due[t['id']], True)
                changed[t['id']] = str(Fraction(str(t['deadline_h'])))
        ledger['construction'] = dict(info, deadlines=changed)
        payload = build_variants(p, cells, direction, (STRENGTHS[ri],), (TIMES[ti],), rule=rule)[0, 0]
        payload['benchmark_id'] = name
        scenario = Scenario(payload)
        # The previous plan must stay feasible under the previous forecast, checked from this
        # state. For a UAV in the air that check can need a little more time than the take-off
        # floor allows; a constructed deadline it rejects rises in doubling steps from 1e-5 h
        # until it is accepted (amended 17 October). Raising a deadline keeps W feasible.
        step, lifts = {}, 0
        while not (premise := previous_premise(scenario))['accepted']:
            match = re.fullmatch(r'conservative constraint: deadline:[^:]+:\d+:(.+)', premise.get('reason') or '')
            task = match.group(1) if match else None
            lifts += 1
            if task not in changed or lifts > 40:
                ledger['reason'] = 'previous_premise_failed'
                return None, ledger
            step[task] = step.get(task, Fraction(1, 2*10**5))*2
            for t in p['mission']['tasks']:
                if t['id'] == task:
                    t['deadline_h'] = _decimal(Fraction(str(t['deadline_h']))+step[task], True)
                    changed[task] = str(Fraction(str(t['deadline_h'])))
            payload = build_variants(p, cells, direction, (STRENGTHS[ri],), (TIMES[ti],), rule=rule)[0, 0]
            payload['benchmark_id'] = name
            scenario = Scenario(payload)
        ledger['construction']['premise_lifts'] = lifts
        if affected_uavs(scenario, diagnose_wind_update(scenario))['uavs'] != u0:
            ledger['reason'] = 'construction_changed_u0'
            return None, ledger
        w, level = witness(payload, plan)
        ledger['construction']['witness_level'] = level
        if level != 4:
            ledger['reason'] = 'construction_witness_failed'
            return None, ledger
        # The screen is the reference method itself, CMI with the arena's settings, for
        # ``screen_seconds`` per round (amended 16 October; it was a 60 s PH search, which missed
        # Level-3 plans CMI finds). Only the best plan it returns is used: a plan P at Level 3
        # or below passed the exact checker, so the draw as it stands cannot be Level 4; its
        # proofs play no part. Tightening: the tasks P delivers later than W get W's times as
        # deadlines, which excludes P and keeps W; then screen again. A draw is rejected when P
        # is no later than W wherever a deadline could drop, or after ``tighten_rounds`` rounds;
        # the screen never rejects a Level-4 draw.
        floor = {t: hi for t, (_, hi) in times.items()}
        rounds = ledger['construction']['tightening'] = []
        while True:
            found = run_arm('CMI', payload, screen_seconds)
            ledger['construction']['screen_plan_level'] = found['plan_level']
            ledger['construction']['screen_bounds'] = dict(lower=found['bounds']['lower'],
                                                           upper=found['bounds']['upper'])
            if found['plan_level'] is None or found['plan_level'] > 3:
                break
            lowered = {} if len(rounds) == tighten_rounds else tighten(
                payload, delivery_times(payload, w), delivery_times(payload, found['plan']['witness']), floor)
            rounds.append(dict(plan_level=found['plan_level'], lowered={t: str(v) for t, v in sorted(lowered.items())}))
            if not lowered:
                ledger['reason'] = f"screen_found_level_{found['plan_level']}"
                return None, ledger
            for t in p['mission']['tasks']:
                if t['id'] in lowered:
                    t['deadline_h'] = _decimal(lowered[t['id']], True)
                    ledger['construction']['deadlines'][t['id']] = str(Fraction(str(t['deadline_h'])))
            payload = build_variants(p, cells, direction, (STRENGTHS[ri],), (TIMES[ti],), rule=rule)[0, 0]
            payload['benchmark_id'] = name
            scenario = Scenario(payload)
            if (not previous_premise(scenario)['accepted']
                    or affected_uavs(scenario, diagnose_wind_update(scenario))['uavs'] != u0):
                ledger['reason'] = 'tightening_changed_premise_or_u0'
                return None, ledger
            w, level = witness(payload, plan)
            if level != 4:
                ledger['reason'] = 'tightening_lost_witness'
                return None, ledger
    screen = level0_screen(scenario, admission_seconds)
    if screen != 'disrupted':
        ledger['reason'] = screen
        return None, ledger
    ledger.update(status='admitted', scenario_hash=scenario.content_hash())
    if recipe in MECHANISMS:
        # Kept with the draw: the labelling stage pools it with the reference label (``level4.pool``).
        ledger['construction']['witness'] = json.loads(json.dumps(w))
    return scenario.to_dict(), ledger


def label_class(label):
    """Class name of a reference label, or None when it is undecided or Level 0. A label pooled
    with its draw's construction witness is read through its pooled bounds."""
    b = (label.get('pooled') or {}).get('bounds') or label['result']['bounds']
    if b['minimum'] == 'infinity':
        return 'infinity'
    if b['minimum'] in (1, 2, 3, 4):
        return str(b['minimum'])
    return None


def select(draws, config):
    """Fill the quotas in draw order. ``draws`` = [(draw id, ledger, label or None)] in order."""
    quota, per_time = config['quota_per_fleet'], math.ceil(config['quota_per_fleet']/3)
    fills = {(c, f, t): [] for c in CLASS_NAMES for f in config['fleets'] for t in TIMES}
    residue = []
    for name, ledger, label in draws:
        if ledger['status'] != 'admitted' or label is None or not label['audit']['ok']:
            continue
        c = label_class(label)
        if c is None:
            if label['result']['bounds']['minimum'] is None:
                residue.append(name)
            continue
        f, t = ledger['fleet'], ledger['time']
        if len(fills[c, f, t]) < per_time and sum(len(fills[c, f, x]) for x in TIMES) < quota:
            fills[c, f, t].append(name)
    rng = random.Random(config.get('residue_seed', 0))
    hard = sorted(rng.sample(sorted(residue), min(config['residue'], len(residue))))
    selected = {c: sorted(n for (cc, f, t), names in fills.items() if cc == c for n in names) for c in CLASS_NAMES}
    full = {f'{c}|{f}': sum(len(fills[c, f, t]) for t in TIMES) >= quota for c in CLASS_NAMES for f in config['fleets']}
    return dict(selected=selected, hard=hard, residue_pool=len(residue), full=full,
                counts={f'{c}|{f}|{t}': len(v) for (c, f, t), v in fills.items()})
